function normalizeKey(code: string): string {
  return code
    .toLowerCase()
    .replace(/^pantone\s+/, '')
    .replace(/\s+(c|u|m|cp|up)$/, '')
    .replace(/(c|u|m)$/, '')
    .trim()
}

/**
 * Returns the approximate hex color for a Pantone code, or null if unknown.
 * Also accepts hex codes directly (#RGB or #RRGGBB).
 */
export function pantoneToHex(code: string): string | null {
  if (!code) return null
  const trimmed = code.trim()
  if (/^#([0-9A-Fa-f]{3}|[0-9A-Fa-f]{6})$/.test(trimmed)) return trimmed
  const key = normalizeKey(trimmed)
  return PANTONE_HEX[key] ?? null
}
